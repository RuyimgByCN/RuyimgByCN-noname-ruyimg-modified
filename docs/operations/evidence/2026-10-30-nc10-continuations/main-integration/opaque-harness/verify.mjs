import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { resolve } from 'node:path';
const [pkg, nativeFile, wasmFile, reportFile] = process.argv.slice(2);
const { default: init, run_opaque_planner_matrix } = await import(pathToFileURL(resolve(pkg, 'nc10_opaque_planner_evidence.js')));
await init({ module_or_path: readFileSync(resolve(pkg, 'nc10_opaque_planner_evidence_bg.wasm')) });
const actual = JSON.parse(run_opaque_planner_matrix());
const expected = JSON.parse(readFileSync(nativeFile, 'utf8'));
writeFileSync(wasmFile, JSON.stringify(actual, null, 2) + '\n');
assert.deepEqual(actual, expected, 'entire shared native/actual-WASM planner output, including public input/events/full Plans and archives');
assert.equal(actual.entrypoint, 'Engine::plan_action');
assert.equal(actual.caseCount, 1);
assert.equal(actual.plannerCalls, 4);
assert.equal(actual.cases[0].prompt, 'rvm_choice');
assert.deepEqual(actual.cases[0].privateLocals.map(row => row.local0), [0, 4]);
assert.deepEqual(actual.cases[0].budgets.map(row => row.budget), [0, 48]);
const report = { passed: true, runtime: 'actual generated wasm32 web-target package initialized by Node', entrypoint: actual.entrypoint, cases: actual.caseCount, prompt: actual.cases[0].prompt, privateLocals: [0, 4], budgets: [0, 48], policyVariant: 1, lookaheadDepth: 2, nativePlannerCalls: 4, wasmPlannerCalls: 4, fullOutputEqual: true, allSourceArchivesImmutable: true, restoredApplyChecksPerTarget: 4, nodesUsed: 0, simFaults: 0, scope: 'First actual opaque rvm_choice planner counterfactual matrix; no author-DSL rvm_discard_pick, generic Host, no-choice storage privacy, or overall NC10 acceptance claim' };
writeFileSync(reportFile, JSON.stringify(report, null, 2) + '\n');
console.log(JSON.stringify(report));
