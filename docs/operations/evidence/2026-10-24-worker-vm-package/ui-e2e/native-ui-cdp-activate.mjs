const targets = await fetch("http://127.0.0.1:9222/json").then((r) => r.json());
const page = targets.find((t) => t.type === "page" && t.url.includes("127.0.0.1:4173"));
const ws = new WebSocket(page.webSocketDebuggerUrl);
let id = 0; const pending = new Map();
ws.onmessage = (e) => { const m = JSON.parse(e.data); if (m.id && pending.has(m.id)) { pending.get(m.id)(m); pending.delete(m.id); } };
await new Promise((res, rej) => { ws.onopen = res; ws.onerror = rej; });
const send = (method, params = {}) => { const i = ++id; ws.send(JSON.stringify({ id: i, method, params })); return new Promise((r) => pending.set(i, r)); };
await send("Runtime.enable");
const click = await send("Runtime.evaluate", { expression: `(() => { const b=[...document.querySelectorAll('button')].find(x=>x.textContent.includes('激活')); if(!b) return 'no-button'; b.click(); return 'clicked'; })()`, returnByValue: true });
console.log("CLICK", click.result?.result?.value);
await new Promise((r) => setTimeout(r, 1000));
const text = await send("Runtime.evaluate", { expression: "document.body.innerText", returnByValue: true });
console.log("AFTER_HAS_DONE", String(text.result?.result?.value ?? "").includes("activate 完成"));
ws.close();
