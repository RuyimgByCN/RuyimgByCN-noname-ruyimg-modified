import assert from 'node:assert/strict';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: "chrome" });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', e => errors.push(String(e)));
const origin = process.env.NONAME_WEB_ORIGIN || 'http://127.0.0.1:5473';
const storeKey = 'noname-next.extension-store.v1';
const savesKey = 'noname-next.native-saves.v1';
const results=[];
const check=(name,detail)=>{results.push({name,detail});console.log(`PASS ${name}: ${detail}`)};
try {
 await page.goto(`${origin}/extensions`);
 assert.equal(await page.title(), '无名杀 Next');
 await page.getByRole('button',{name:'全部安装并启用',exact:true}).click();
 const catalogCount = await page.locator('.trow').count();
 const installed=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),storeKey);
 assert.equal(installed.contentLock.length,catalogCount);
 assert.ok(installed.installed.every(r=>r.nativeVersions[r.version]));
 check('ui_install_actual_copies',installed.contentLock.length);
 await page.goto(`${origin}/battle?players=4&seed=4242&skipAnims=1`);
 await page.getByRole('button', {name:/^选择 ddd刘冲/}).waitFor({timeout:30000});
 const candidate=page.locator('button.candidate').filter({hasText:/ddd刘冲/}).first();
 const name=await candidate.locator('.candidate-name').textContent();
 await candidate.click();
 await page.locator('.general-select .success').waitFor();
 check('ui_formal_start_and_extension_general',name);
 await page.getByRole('button',{name:'存档',exact:true}).click();
 await page.waitForFunction(k=>!!localStorage.getItem(k),savesKey);
 const saved=await page.evaluate(k=>JSON.parse(localStorage.getItem(k))[0],savesKey);
 assert.equal(saved.contentLock.length,catalogCount);
 assert.equal(JSON.parse(saved.packsJson).length,catalogCount);
 check('ui_save_frozen_payload',saved.hex.length/2);
 await page.goto(`${origin}/extensions`);
 await page.getByRole('button',{name:'卸载',exact:true}).first().click();
 const after=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),storeKey);
 assert.equal(after.installed.length,catalogCount - 1);
 assert.equal(after.matchFrozen,false);
 await page.goto(`${origin}/battle?players=4&seed=888&skipAnims=1`);
 await page.getByRole('button',{name:'存档',exact:true}).waitFor();
 await page.waitForFunction(()=>!document.querySelector('section.toolbar button').disabled);
 await page.getByRole('button',{name:'读档',exact:true}).click();
 await page.waitForFunction(()=>document.body.innerText.includes('读档 save-'));
 assert.ok(await page.getByRole('button',{name:new RegExp(`选择 ${name}`)}).count());
 await page.getByRole('button',{name:'存档',exact:true}).click();
 const resaved=await page.evaluate(k=>JSON.parse(localStorage.getItem(k))[0],savesKey);
 assert.equal(resaved.packsJson,saved.packsJson);
 assert.equal(resaved.seed,4242);
 check('ui_restore_after_uninstall_and_resave_original_lock',resaved.contentLock.length);
 await page.screenshot({path:join(dirname(fileURLToPath(import.meta.url)), 'browser-formal-match.png'),fullPage:true});
 await page.goto(`${origin}/extensions`);
 await page.getByRole('button',{name:'全部安装并启用',exact:true}).click();
 await page.goto(`${origin}/battle?mode=identity&players=4&seed=4242&skipAnims=1`);
 await page.getByRole('button', {name:/^选择 ddd刘冲/}).waitFor({timeout:30000});
 assert.ok(await page.locator('button.candidate').filter({hasText:/ddd刘冲/}).count());
 await page.getByRole('button',{name:'存档',exact:true}).click();
 check('ui_identity_with_installed_extensions','started and saved');
 await page.goto(`${origin}/extensions`);
 await page.evaluate(k=>{const s=JSON.parse(localStorage.getItem(k));delete s.installed[0].nativeVersions;localStorage.setItem(k,JSON.stringify(s))},storeKey);
 await page.goto(`${origin}/battle?players=4&seed=42&skipAnims=1`);
 await page.getByText(/缺少已安装包内容/).first().waitFor();
 const failed=await page.evaluate(k=>JSON.parse(localStorage.getItem(k)),storeKey);
 assert.equal(failed.matchFrozen,false);
 assert.equal(await page.getByRole('button',{name:'存档',exact:true}).isDisabled(),true);
 check('ui_missing_payload_fails_and_unfreezes','no standard fallback');
 assert.deepEqual(errors,[]);
 check('page_errors',errors.length);
 console.log(JSON.stringify({origin,results},null,2));
} finally { await browser.close(); }
